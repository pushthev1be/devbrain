/**
 * Regenerate packages/mcp/src/stackIcons.ts from the simple-icons package.
 *
 *   npm run icons
 *
 * The labels come from ALL_STACK_LABELS in core, not from a list kept here, so
 * adding a framework to detectStack is the only edit needed to get a mark for
 * it. The slug, the brand colour and the path all come out of the package —
 * none of it is typed by hand, because a hand-typed hex is a hex that goes
 * stale silently when a brand changes.
 *
 * Only `role` is a judgement, and that is what ROLES below is for. A label with
 * no role is reported here and fails the test in stackIcons.test.ts, so a new
 * framework cannot quietly render as nothing — which is exactly what happened
 * to tRPC, GraphQL and Socket.io when this table was first written by hand.
 */

import { writeFileSync } from 'fs';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const simpleIcons = require('simple-icons');
const { ALL_STACK_LABELS } = require('../packages/core/dist/stack.js');

/** How a label is placed in the row: written in, built with, stores in, built by. */
const ROLES = {
  'Node.js': 'lang', 'TypeScript': 'lang', 'Python': 'lang', 'Rust': 'lang',
  'Go': 'lang', 'Ruby': 'lang', 'Java': 'lang', 'C#/.NET': 'lang',

  'React': 'frontend', 'Vue': 'frontend', 'Angular': 'frontend',
  'Svelte': 'frontend', 'Next.js': 'frontend', 'Nuxt': 'frontend',
  'React Native': 'frontend', 'Expo': 'frontend', 'Electron': 'frontend',
  'Tailwind CSS': 'frontend',

  'Express': 'backend', 'Fastify': 'backend', 'NestJS': 'backend',
  'Hono': 'backend', 'tRPC': 'backend', 'GraphQL': 'backend', 'Socket.io': 'backend',

  'Prisma': 'data', 'MongoDB/Mongoose': 'data', 'TypeORM': 'data',
  'Sequelize': 'data', 'Drizzle ORM': 'data',

  'Vite': 'build', 'Webpack': 'build',
};

/**
 * Slugs that the naming rule below cannot reach.
 *
 * Kept deliberately short: everything not listed is derived, so this holds only
 * the genuine exceptions rather than a second copy of the whole table.
 */
const SLUG_OVERRIDES = {
  'Vue': 'vuedotjs',
  'Java': 'openjdk',
  'C#/.NET': 'dotnet',
  'MongoDB/Mongoose': 'mongodb',
  'Drizzle ORM': 'drizzle',
  'React Native': 'react',
  'Socket.io': 'socketdotio',
};

/** Simple Icons' own convention: lower case, a dot spelled "dot", nothing else. */
function slugFor(label) {
  return SLUG_OVERRIDES[label]
    ?? label.toLowerCase().replace(/\./g, 'dot').replace(/[^a-z0-9]/g, '');
}

function iconFor(slug) {
  const key = 'si' + slug.charAt(0).toUpperCase() + slug.slice(1);
  return simpleIcons[key];
}

const icons = {};
const noMark = [];
const noRole = [];

for (const label of ALL_STACK_LABELS) {
  const role = ROLES[label];
  if (!role) noRole.push(label);
  const icon = iconFor(slugFor(label));
  if (!icon) { noMark.push(`${label} (tried "${slugFor(label)}")`); continue; }
  icons[label] = {
    d: `<path d="${icon.path}"/>`,
    role: role ?? 'build',
    color: `#${icon.hex}`,
  };
}

const header = `// Brand marks for detected stack entries, from Simple Icons (CC0).
//
// GENERATED by scripts/gen-stack-icons.mjs — run \`npm run icons\` rather than
// editing this file. Slug, colour and path all come from the package, so a
// brand changing its colour is one regeneration away rather than a hand edit.
//
// Lucide is a generic icon set and carries no logos by design, which is why
// these come from a second source and need their own wrapper: single-path
// glyphs on a 24x24 box using fill, where Lucide is stroked.
//
// Keyed by exactly the label detectStack produces, so a stack entry either has
// its own mark or renders as nothing — never as the wrong logo.

export interface StackIcon {
  /** Inner SVG markup, 24x24, fill-based. */
  d: string;
  /** Orders the row: what it is written in, built with, stores in, built by. */
  role: 'lang' | 'frontend' | 'backend' | 'data' | 'build';
  /** The brand's own colour, used at low opacity until hovered. */
  color: string;
}

export const STACK_ICONS: Record<string, StackIcon> = `;

writeFileSync(
  new URL('../packages/mcp/src/stackIcons.ts', import.meta.url),
  header + JSON.stringify(icons, null, 2) + ';\n',
);

console.log(`stackIcons.ts: ${Object.keys(icons).length} of ${ALL_STACK_LABELS.length} labels have a mark`);
if (noRole.length) console.log(`  no role assigned (add to ROLES): ${noRole.join(', ')}`);
if (noMark.length) console.log(`  no icon in simple-icons: ${noMark.join(', ')}`);
